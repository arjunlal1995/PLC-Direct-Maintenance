export interface ModbusPacketLog {
  id: string;
  timestamp: number;
  direction: 'TX_REQUEST' | 'RX_RESPONSE';
  functionCode: 'FC01_READ_COILS' | 'FC03_READ_HOLDING' | 'FC04_READ_INPUT' | 'FC06_WRITE_SINGLE' | 'FC16_WRITE_MULTIPLE';
  unitId: number;
  startAddress: number;
  quantity: number;
  hexPayload: string;
  crc16: string;
  latencyMs: number;
  status: 'SUCCESS' | 'CRC_ERROR' | 'TIMEOUT';
}

export function generateSimulatedModbusTraffic(lastPacketId: number = 0): ModbusPacketLog {
  const fcs: ModbusPacketLog['functionCode'][] = ['FC03_READ_HOLDING', 'FC01_READ_COILS', 'FC04_READ_INPUT'];
  const fc = fcs[Math.floor(Math.random() * fcs.length)];
  const isTx = Math.random() > 0.5;
  const startAddr = fc === 'FC03_READ_HOLDING' ? 100 : 0;
  const qty = 8;
  const latency = Math.floor(8 + Math.random() * 12);
  
  return {
    id: `PKT-${Date.now().toString().slice(-6)}-${lastPacketId}`,
    timestamp: Date.now(),
    direction: isTx ? 'TX_REQUEST' : 'RX_RESPONSE',
    functionCode: fc,
    unitId: 1,
    startAddress: startAddr,
    quantity: qty,
    hexPayload: isTx 
      ? `00 01 00 00 00 06 01 03 ${startAddr.toString(16).padStart(4, '0')} ${qty.toString(16).padStart(4, '0')}`
      : `00 01 00 00 00 13 01 03 10 00 55 00 41 02 C1 00 90 00 46 00 91 00 8E 00 87`,
    crc16: '0x' + Math.floor(0x1000 + Math.random() * 0xEFFF).toString(16).toUpperCase(),
    latencyMs: latency,
    status: 'SUCCESS'
  };
}
